/** S-1…S-7: vendoring of the Axyome XM readers. */
import { createHash } from 'crypto';
import * as fs from 'fs';
import * as path from 'path';
import { pathToFileURL } from 'url';
import { beforeAll, describe, expect, it } from 'vitest';
import { tmpDir } from './helpers';

interface SyncModule {
    stripComments(rel: string, source: string): string;
    syncXmCore(o: { srcRoot?: string; outRoot?: string; check?: boolean; files?: readonly string[]; commit?: string }): string[];
    XM_CORE_FILES: readonly string[];
    DEFAULT_SRC_ROOT: string;
    DEFAULT_OUT_ROOT: string;
}

let m: SyncModule;
beforeAll(async () => {
    m = (await import(pathToFileURL(path.join(__dirname, '..', 'scripts', 'sync-xm-core.mjs')).href)) as SyncModule;
});

const LIST = [
    'capture/claude-code-parser.ts', 'capture/codex/codex-commands.ts', 'capture/codex/codex-dialect.ts',
    'capture/codex/codex-discovery.ts', 'capture/codex/codex-fs.ts', 'capture/codex/codex-home.ts',
    'capture/codex/codex-parser.ts', 'capture/codex/codex-patch.ts', 'capture/codex/codex-redact.ts',
    'types/claude-code.ts', 'types/codex.ts', 'utils/jsonl-session-parser.ts', 'utils/session-markdown-generator.ts',
];

// The Axyome XM sources exist only in the private source tree, not in the public repository.
const XM_SOURCES = fs.existsSync(path.join(__dirname, '..', '..', 'mem-ag-basic', 'src'));

describe.skipIf(!XM_SOURCES)('syncXmCore', () => {
    it('S-1 copies exactly the 13 allow-listed files', () => {
        const out = tmpDir();
        const written = m.syncXmCore({ outRoot: out, commit: 'test' });
        expect([...m.XM_CORE_FILES]).toEqual(LIST);
        expect(written.sort()).toEqual([...LIST].sort());
        for (const rel of LIST) { expect(fs.existsSync(path.join(out, rel))).toBe(true); }
    });

    it('S-2 writes the header and a manifest whose source hashes equal the XM files', () => {
        const out = tmpDir();
        m.syncXmCore({ outRoot: out, commit: 'test' });
        const manifest = JSON.parse(fs.readFileSync(path.join(out, 'MANIFEST.json'), 'utf8')) as { files: { path: string; sourceSha256: string }[] };
        expect(manifest.files).toHaveLength(13);
        for (const f of manifest.files) {
            const src = fs.readFileSync(path.join(m.DEFAULT_SRC_ROOT, f.path));
            expect(f.sourceSha256).toBe(createHash('sha256').update(src).digest('hex'));
            const text = fs.readFileSync(path.join(out, f.path), 'utf8');
            expect(text.startsWith(`// Vendored from Axyome XM (src/${f.path}), source sha256 ${f.sourceSha256}. GENERATED by scripts/sync-xm-core.mjs: do not edit here.\n`)).toBe(true);
            // Only the generated header line is a comment (PX-2).
            expect(text.split('\n').slice(1).join('\n')).not.toMatch(/^\s*(\/\/|\/\*)/m);
        }
    });

    it('S-3 rewrites the blob-storage type import to the shim', () => {
        const out = tmpDir();
        m.syncXmCore({ outRoot: out, commit: 'test' });
        const text = fs.readFileSync(path.join(out, 'utils/session-markdown-generator.ts'), 'utf8');
        expect(text).toContain("from '../shims/blob-storage-types'");
        expect(text).not.toContain('../services/blob-storage');
    });

    it('S-4 check mode reports a drifted file and writes nothing', () => {
        const out = tmpDir();
        m.syncXmCore({ outRoot: out, commit: 'test' });
        const target = path.join(out, 'utils/jsonl-session-parser.ts');
        fs.appendFileSync(target, '\n// local edit\n');
        const before = fs.statSync(target).mtimeMs;
        const changed = m.syncXmCore({ outRoot: out, check: true, commit: 'test' });
        expect(changed).toEqual(['utils/jsonl-session-parser.ts']);
        expect(fs.statSync(target).mtimeMs).toBe(before);
        expect(fs.readFileSync(target, 'utf8')).toContain('// local edit');
    });

    it('S-5 the import guard refuses an import outside the vendored set', () => {
        const src = tmpDir();
        fs.mkdirSync(path.join(src, 'types'), { recursive: true });
        fs.writeFileSync(path.join(src, 'types', 'claude-code.ts'), "import { open } from '../storage/db';\nexport const x = open;\n");
        expect(() => m.syncXmCore({ srcRoot: src, outRoot: tmpDir(), files: ['types/claude-code.ts'], commit: 'test' }))
            .toThrow(/outside the vendored set/);
    });

    it('S-6 the committed src/xm-core is in sync with Axyome XM', () => {
        expect(m.syncXmCore({ check: true, commit: 'test' })).toEqual([]);
    });

    it('S-7 (PX-T1) a vendored file keeps its code and loses every comment; --check then passes', () => {
        const src = tmpDir();
        fs.mkdirSync(path.join(src, 'types'), { recursive: true });
        const code = "/** Plan: internal/x */\nimport * as fs from 'fs';\n// note\nexport const url = 'http://a/b'; /* tail */\nexport const n = fs.constants.F_OK;\n";
        fs.writeFileSync(path.join(src, 'types', 'claude-code.ts'), code);
        const out = tmpDir();
        m.syncXmCore({ srcRoot: src, outRoot: out, files: ['types/claude-code.ts'], commit: 'test' });
        const text = fs.readFileSync(path.join(out, 'types', 'claude-code.ts'), 'utf8');
        expect(text).toMatch(/^\/\/ Vendored from Axyome XM \(src\/types\/claude-code\.ts\)/);
        expect(text).not.toContain('Plan:');
        expect(text).not.toContain('note');
        expect(text).not.toContain('tail');
        expect(text).toContain("export const url = 'http://a/b';");
        expect(text).toContain('export const n = fs.constants.F_OK;');
        expect(m.syncXmCore({ srcRoot: src, outRoot: out, files: ['types/claude-code.ts'], check: true, commit: 'test' })).toEqual([]);
    });
});
