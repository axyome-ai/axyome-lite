#!/usr/bin/env node
/**
 * Vendor the Axyome XM reader files into Axyome Lite.
 *
 *   node scripts/sync-xm-core.mjs            copy the allow-listed files into src/xm-core/
 *   node scripts/sync-xm-core.mjs --check    write nothing; exit 1 and list every file that differs
 *
 * The files keep their XM layout under src/xm-core/. Each gets a one-line header (source path, source
 * sha256, "generated") and is printed without comments (TypeScript printer), so none of XM's internal
 * comments is published. One type-only import is rewritten to a local shim. An import guard refuses any
 * import outside the vendored set, the shim or the allowed Node built-ins.
 *
 * The XM sources exist only in the Axyome XM repository. Where they are absent (this public repository),
 * --check reports that and exits 0: the committed src/xm-core is the source of truth there.
 */
import { createHash } from 'crypto';
import { execFileSync } from 'child_process';
import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';
import ts from 'typescript';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const PKG_ROOT = path.resolve(HERE, '..');
export const DEFAULT_SRC_ROOT = path.resolve(PKG_ROOT, '..', 'mem-ag-basic', 'src');
export const DEFAULT_OUT_ROOT = path.join(PKG_ROOT, 'src', 'xm-core');

/** The 13 reader files (the value-import closure of the readers Lite uses, measured 2026-11-23). */
export const XM_CORE_FILES = Object.freeze([
    'capture/claude-code-parser.ts',
    'capture/codex/codex-commands.ts',
    'capture/codex/codex-dialect.ts',
    'capture/codex/codex-discovery.ts',
    'capture/codex/codex-fs.ts',
    'capture/codex/codex-home.ts',
    'capture/codex/codex-parser.ts',
    'capture/codex/codex-patch.ts',
    'capture/codex/codex-redact.ts',
    'types/claude-code.ts',
    'types/codex.ts',
    'utils/jsonl-session-parser.ts',
    'utils/session-markdown-generator.ts',
]);

/** Type-only imports replaced by a local shim: [file, from, to]. */
export const REWRITES = Object.freeze([
    ['utils/session-markdown-generator.ts', "'../services/blob-storage'", "'../shims/blob-storage-types'"],
]);

export const SHIMS = Object.freeze(['shims/blob-storage-types.ts']);
export const ALLOWED_BUILTINS = Object.freeze(['fs', 'fs/promises', 'path', 'crypto']);

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

function header(rel, srcSha) {
    return `// Vendored from Axyome XM (src/${rel}), source sha256 ${srcSha}. GENERATED by scripts/sync-xm-core.mjs: do not edit here.\n`;
}

/** The source printed again by the TypeScript compiler, without any comment. */
export function stripComments(rel, source) {
    const sf = ts.createSourceFile(rel, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
    return ts.createPrinter({ removeComments: true, newLine: ts.NewLineKind.LineFeed }).printFile(sf);
}

/** Every import / export-from / dynamic import specifier in a TS source. */
export function importSpecifiers(source) {
    const out = [];
    const re = /(?:^|\n)\s*(?:import|export)\s[^;]*?from\s+'([^']+)'|import\(\s*'([^']+)'\s*\)/g;
    let m;
    while ((m = re.exec(source))) { out.push(m[1] ?? m[2]); }
    return out;
}

/** Throws when a vendored file imports anything outside the vendored set, the shims or the allowed built-ins. */
export function guardImports(rel, source, vendored = XM_CORE_FILES, shims = SHIMS) {
    const known = new Set([...vendored, ...shims].map((f) => f.replace(/\.ts$/, '')));
    for (const spec of importSpecifiers(source)) {
        if (spec.startsWith('.')) {
            const target = path.posix.normalize(path.posix.join(path.posix.dirname(rel), spec)).replace(/\.js$/, '');
            if (!known.has(target)) {
                throw new Error(`${rel}: import '${spec}' resolves to '${target}', outside the vendored set`);
            }
        } else if (!ALLOWED_BUILTINS.includes(spec)) {
            throw new Error(`${rel}: import '${spec}' is outside the vendored set (allowed built-ins: ${ALLOWED_BUILTINS.join(', ')})`);
        }
    }
}

/** The vendored text for one file (header + rewritten body, comments removed). */
export function vendorText(rel, srcBuf) {
    let body = srcBuf.toString('utf8');
    for (const [file, from, to] of REWRITES) {
        if (file !== rel) { continue; }
        if (!body.includes(from)) { throw new Error(`${rel}: expected import ${from} to rewrite`); }
        body = body.split(from).join(to);
    }
    guardImports(rel, body);
    return header(rel, sha256(srcBuf)) + stripComments(rel, body);
}

function gitHead(cwd) {
    try { return execFileSync('git', ['rev-parse', 'HEAD'], { cwd, encoding: 'utf8' }).trim(); } catch { return 'unknown'; }
}

/**
 * Copy (or, with check, compare) the vendored files.
 * @returns {string[]} the relative paths that differ (check mode) or were written (write mode)
 */
export function syncXmCore({ srcRoot = DEFAULT_SRC_ROOT, outRoot = DEFAULT_OUT_ROOT, check = false, files = XM_CORE_FILES, commit } = {}) {
    const changed = [];
    const manifest = { generatedBy: 'scripts/sync-xm-core.mjs', sourceRoot: 'Axyome XM src', sourceCommit: commit ?? gitHead(srcRoot), files: [] };
    for (const rel of files) {
        const srcBuf = fs.readFileSync(path.join(srcRoot, rel));
        const text = vendorText(rel, srcBuf);
        const dest = path.join(outRoot, rel);
        const current = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : null;
        if (current !== text) {
            changed.push(rel);
            if (!check) {
                fs.mkdirSync(path.dirname(dest), { recursive: true });
                fs.writeFileSync(dest, text);
            }
        }
        manifest.files.push({ path: rel, sourceSha256: sha256(srcBuf), outputSha256: sha256(Buffer.from(text, 'utf8')) });
    }
    const manifestPath = path.join(outRoot, 'MANIFEST.json');
    if (check) {
        if (!fs.existsSync(manifestPath)) {
            changed.push('MANIFEST.json');
        } else {
            const cur = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
            if (JSON.stringify(cur.files) !== JSON.stringify(manifest.files)) { changed.push('MANIFEST.json'); }
        }
    } else {
        fs.mkdirSync(outRoot, { recursive: true });
        fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
    }
    return changed;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
    const check = process.argv.includes('--check');
    if (!fs.existsSync(DEFAULT_SRC_ROOT)) {
        console.log('Axyome XM sources not present here: nothing to sync (src/xm-core is committed as is)');
        process.exit(check ? 0 : 1);
    }
    try {
        const changed = syncXmCore({ check });
        if (check) {
            if (changed.length) {
                console.error(`xm-core out of sync (${changed.length}): ${changed.join(', ')}\nRun: npm run sync`);
                process.exit(1);
            }
            console.log(`xm-core in sync (${XM_CORE_FILES.length} files)`);
        } else {
            console.log(`xm-core: ${changed.length} file(s) written of ${XM_CORE_FILES.length}; MANIFEST.json updated`);
        }
    } catch (e) {
        console.error(String(e && e.message ? e.message : e));
        process.exit(1);
    }
}
